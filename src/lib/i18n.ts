export function translate(language: Language, text: string, variables?: Record<string, string | number>) {
  const template = language === "id" ? (indonesian[text] ?? text) : text;
  if (!variables) return template;
  return Object.entries(variables).reduce((result, [key, value]) => result.replaceAll(`{${key}}`, String(value)), template);
}
